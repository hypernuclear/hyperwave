"""Turn an SVG mark into a QML component whose colour is a property.

    python3 scripts/gen_mark.py assets/hyperwave.svg qml/HyperwaveMark.qml \\
        HyperwaveMark "The hyperwave mark."

A Shape rather than an Image, because an Image bakes the artwork's own fill in.
Recolouring one afterwards means MultiEffect, and MultiEffect cannot lighten:
its colorization multiplies the source by the target colour, so black stays
black however white you ask for. A Shape simply takes a colour.

Every path is emitted as a PathSvg carrying the SVG's own `d` string verbatim,
rather than being parsed into PathLine/PathCubic elements. That is the whole
reason this is short: Illustrator writes relative commands (`c`, `s`, `l`), and
a hand-written parser either has to implement all of them or refuse the file.
Qt already has that parser.

Regenerate after changing artwork; the output is checked in so a build needs
neither this script nor Python.
"""
import re
import sys

TEMPLATE = '''// {doc}
//
// GENERATED by scripts/gen_mark.py from {src} -- edit the artwork, not this.
//
// A Shape rather than an Image so the colour is a property: this sits on a busy
// illustration in one place and could sit on anything later, and a baked-in
// black would be invisible on half of them.
import QtQuick
import QtQuick.Shapes

Item {{
    id: root

    /// Fill colour. No default that works on both a light and a dark ground,
    /// so the caller always decides.
    property color color: "#ffffff"

    /// The artwork's own coordinate space, exposed so a caller can hold the
    /// aspect ratio without hard-coding numbers that would go stale with the
    /// next export.
    readonly property real viewWidth: {w}
    readonly property real viewHeight: {h}
    implicitWidth: viewWidth
    implicitHeight: viewHeight

    Shape {{
        anchors.fill: parent
        preferredRendererType: Shape.CurveRenderer
        antialiasing: true
        smooth: true
        // Authored in the SVG's own coordinate space; scaled to whatever size
        // the item was given rather than making every caller do the arithmetic.
        transform: Scale {{
            xScale: root.width / root.viewWidth
            yScale: root.height / root.viewHeight
        }}
{body}
    }}
}}
'''

SHAPE_PATH = '''        ShapePath {{
            fillColor: root.color
            strokeColor: "transparent"
            // The SVG's default, and what these exports rely on for counters --
            // the hole in a "p" is a subpath wound the other way, not a
            // separate shape.
            fillRule: ShapePath.OddEvenFill
            PathSvg {{ path: "{d}" }}
        }}'''


def generate(svg, src, doc):
    box = re.search(r'viewBox="([\d.\-\s]+)"', svg)
    if not box:
        sys.exit(f"{src}: no viewBox, so there is no coordinate space to scale from")
    _, _, w, h = box.group(1).split()

    paths = re.findall(r'<path[^>]*\sd="([^"]+)"', svg)
    if not paths:
        sys.exit(f"{src}: no <path> elements")

    body = "\n".join(
        SHAPE_PATH.format(d=" ".join(d.split())) for d in paths)
    return TEMPLATE.format(doc=doc, src=src, w=w, h=h, body=body), len(paths)


if __name__ == "__main__":
    if len(sys.argv) != 5:
        sys.exit(__doc__)
    src, out, _component, doc = sys.argv[1:5]
    qml, n = generate(open(src).read(), src, doc)
    open(out, "w").write(qml)
    print(f"{out}: {n} paths")
